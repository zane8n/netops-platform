from netops_platform.traffic_graphers import Grapher, get_grapher, grapher_names

#: Name of the generated file holding the token that gates a non-loopback
#: VictoriaMetrics. Public: anything that needs to authenticate reads it.
VM_CREDENTIAL_FILE = "victoriametrics.auth"
VM_CREDENTIAL_USER = "netrune"


def _victoriametrics_credential(root: Path) -> str:
    """The shared token gating a non-loopback VictoriaMetrics.

    Generated once and kept: regenerating it on every `stack init` would
    silently invalidate every remote poller's already-distributed push URL.
    """
    path = root / VM_CREDENTIAL_FILE
    existing = path.read_text(encoding="utf-8").strip() if path.is_file() else ""
    return existing or secrets.token_urlsafe(24)

DEFAULT_EXPORTER_BIND = "127.0.0.1:9713"
DEFAULT_VM_URL = "http://127.0.0.1:8428"

# A rate window must span at least two scrapes or it resolves to nothing. Four
# times the scrape interval keeps a single missed scrape from blanking a panel.
RATE_WINDOW = "2m"


#: The labels storage attaches when it scrapes. Anything that writes readings
#: by another route has to attach the same ones, or the same port ends up as two
#: series that differ only in scrape plumbing -- and a vector match on the labels
#: that identify a port then finds two candidates and refuses to evaluate, which
#: is every chart on the board going blank at once.
SCRAPE_JOB = "netrune"
SCRAPE_INSTANCE = "netrune-collector"
SCRAPE_SOURCE = "netrune"


def scrape_config(bind: str, scrape_interval: int) -> str:
    host, _, port = bind.rpartition(":")
    return f"""# Generated by 'netrune traffic stack init'.
#
# The scrape interval must not be longer than the shortest watch interval, or
# readings the collector took will be overwritten before they are stored.
global:
  scrape_interval: {scrape_interval}s
  external_labels:
    source: {SCRAPE_SOURCE}

scrape_configs:
  - job_name: {SCRAPE_JOB}
    metrics_path: /metrics
    static_configs:
      - targets: ["{host or '127.0.0.1'}:{port}"]
        labels:
          instance: {SCRAPE_INSTANCE}
"""


def alert_rules() -> str:
    return f"""# Generated by 'netrune traffic stack init'.
#
# Alerting lives here rather than in the dashboard, so an alert fires whether or
# not anyone has a browser open.
groups:
  - name: netrune-collector
    interval: 30s
    rules:
      - alert: NetruneCollectorStopped
        expr: time() - max(netrune_interface_last_poll_timestamp_seconds) by (collector) > 300
        for: 5m
        labels:
          severity: critical
        annotations:
          summary: "Netrune collector {{{{ $labels.collector }}}} has stopped collecting"
          description: "No interface has been polled for over 5 minutes. Every graph below is stale."

      - alert: NetruneInterfaceStale
        expr: |
          (time() - netrune_interface_last_poll_timestamp_seconds > 300)
          and on (device, interface) (netrune_interface_watch_enabled == 1)
        for: 10m
        labels:
          severity: warning
        annotations:
          summary: "{{{{ $labels.device }}}} {{{{ $labels.interface }}}} is not being collected"
          description: "The interface is on the watchlist and enabled, but no reading has arrived for 10 minutes."

  - name: netrune-interfaces
    interval: 30s
    rules:
      - alert: NetruneInterfaceDown
        expr: netrune_interface_up == 0 and netrune_interface_admin_up == 1
        for: 2m
        labels:
          severity: critical
        annotations:
          summary: "{{{{ $labels.device }}}} {{{{ $labels.interface }}}} is down"
          description: "The interface is administratively up but operationally down."

      - alert: NetruneInterfaceSaturated
        expr: |
          100 * 8 * (
            rate(netrune_interface_receive_bytes_total[{RATE_WINDOW}])
            + rate(netrune_interface_transmit_bytes_total[{RATE_WINDOW}])
          ) / netrune_interface_speed_bits > 85
        for: 10m
        labels:
          severity: warning
        annotations:
          summary: "{{{{ $labels.device }}}} {{{{ $labels.interface }}}} is above 85% of link speed"
          description: "Sustained utilisation over ten minutes. Check for a saturated uplink."

      - alert: NetruneInterfaceErrors
        expr: rate(netrune_interface_receive_errors_total[{RATE_WINDOW}]) > 1
        for: 15m
        labels:
          severity: warning
        annotations:
          summary: "{{{{ $labels.device }}}} {{{{ $labels.interface }}}} is taking input errors"
          description: "Sustained input errors usually mean a cable, optic, or duplex problem rather than load."

  - name: netrune-reachability
    interval: 30s
    rules:
      - alert: NetruneTargetUnreachable
        expr: netrune_icmp_up == 0
        for: 3m
        labels:
          severity: critical
        annotations:
          summary: "{{{{ $labels.target }}}} is unreachable from {{{{ $labels.collector }}}}"

      - alert: NetruneTargetPacketLoss
        expr: netrune_icmp_loss_ratio > 0.05
        for: 10m
        labels:
          severity: warning
        annotations:
          summary: "{{{{ $labels.target }}}} is losing packets from {{{{ $labels.collector }}}}"
          description: "Over 5% sustained loss. Latency graphs on this target are not trustworthy while this holds."
"""


#: What a machine is for. A laptop stores, queries, and draws; a poller only
#: has to be somewhere the switches can be reached from.
ROLE_FULL = "full"
ROLE_COLLECTOR = "collector"
ROLES = (ROLE_FULL, ROLE_COLLECTOR)


def _collector_unit(netrune: str) -> str:
    return f"""[Unit]
Description=Netrune traffic collector
Documentation=man:netrune(1)
PartOf=netrune-metrics.target

[Service]
Type=simple
ExecStart={netrune} traffic daemon
# SIGTERM is handled the same way as Ctrl+C, so the collector removes its own
# pidfile rather than leaving one that claims it is still running.
KillSignal=SIGTERM
TimeoutStopSec=20
Restart=always
RestartSec=15
Environment=NETRUNE_PROGRESS=0

[Install]
WantedBy=netrune-metrics.target
"""


def systemd_units(root: Path, bind: str, vm_url: str, retention: str,
                  netrune: str, victoria_metrics: str, vmalert: str,
                  grapher_unit: str = "", confirmed_bind: bool = False,
                  role: str = ROLE_FULL, export_path: str = "", push_url: str = "",
                  export_every: str = "15min", export_window: str = "48h",
                  push_every: str = "1min", storage_bind: str = "") -> Dict[str, str]:
    # A confirmed non-loopback storage bind (--accept-push) exposes
    # VictoriaMetrics's full HTTP API -- query, import, and admin/delete --
    # to anything that can reach it. Basic Auth is the one thing standing
    # between that and an open read/write/delete surface on the network.
    vm_auth = (f" -httpAuth.username={VM_CREDENTIAL_USER} "
               f"-httpAuth.password=file://{root / VM_CREDENTIAL_FILE}") if storage_bind else ""
    """User services, so the stack survives a logout without needing root.

    Ordering matters on a cold start: the exposition must be listening before
    VictoriaMetrics scrapes it, or the first scrapes record the collector as
    down. `Wants=` rather than `Requires=` throughout, so one component failing
    degrades the stack instead of stopping it.

    A collector-role machine gets the collector alone. A poller exists because
    SNMP and ICMP have to originate from the monitored network; it is not where
    anybody looks at a graph. Storing and querying there would mean a second
    time-series database to keep, patch, and give disk to, and an exposition
    listening on a network it was put on to observe rather than to serve. The
    laptop pulls the readings over SSH and keeps them once.
    """
    if role not in ROLES:
        raise ValueError(f"unknown role '{role}'; choose from {', '.join(ROLES)}")
    if role == ROLE_COLLECTOR:
        return {
            "netrune-metrics.target": """[Unit]
Description=Netrune collector
Wants=netrune-collector.service

[Install]
WantedBy=default.target
""",
            "netrune-collector.service": _collector_unit(netrune),
            # Nobody logs into a poller to tidy up, so the tidying is a unit.
            # Without it the readings a laptop already pulled stay on the poller
            # until the disk decides the matter.
            "netrune-prune.service": f"""[Unit]
Description=Netrune retention prune
Documentation=man:netrune(1)

[Service]
Type=oneshot
ExecStart={netrune} db prune --confirm
Environment=NETRUNE_PROGRESS=0
""",
            **({"netrune-export.service": f"""[Unit]
Description=Netrune reading export
Documentation=man:netrune(1)

[Service]
Type=oneshot
# Written to a temporary name and moved into place, so whatever reads the file
# never catches a half-written one -- a sync tool watching the directory will
# copy the moment it changes.
ExecStart=/bin/sh -c '{netrune} traffic export --since {export_window} > "{export_path}.part" && mv "{export_path}.part" "{export_path}"'
Environment=NETRUNE_PROGRESS=0
""",
                "netrune-export.timer": f"""[Unit]
Description=Netrune reading export, every {export_every}

[Timer]
OnBootSec=2min
OnUnitActiveSec={export_every}
Persistent=true

[Install]
WantedBy=timers.target
"""} if export_path else {}),
            **({"netrune-push.service": f"""[Unit]
Description=Netrune reading push
Documentation=man:netrune(1)

[Service]
Type=oneshot
ExecStart={netrune} traffic push --to {push_url}
Environment=NETRUNE_PROGRESS=0
""",
                "netrune-push.timer": f"""[Unit]
Description=Netrune reading push, every {push_every}

[Timer]
OnBootSec=1min
OnUnitActiveSec={push_every}
Persistent=true

[Install]
WantedBy=timers.target
"""} if push_url else {}),
            "netrune-prune.timer": """[Unit]
Description=Netrune retention prune, daily

[Timer]
OnCalendar=daily
# A poller that was switched off overnight still prunes when it comes back,
# rather than waiting a full day for the next window.
Persistent=true
RandomizedDelaySec=30m

[Install]
WantedBy=timers.target
""",
        }
    grapher_want = f"Wants={grapher_unit}" if grapher_unit else "# no grapher selected"
    # A service cannot answer a confirmation prompt at start time, so consent for
    # a non-loopback bind is taken once, from the operator running the generator,
    # and carried into the unit. Deriving it from the address instead would let
    # `stack init --bind 0.0.0.0:9713` publish the exposition with nobody having
    # agreed to it.
    exporter_confirm = " --confirm" if confirmed_bind else ""
    return {
        "netrune-metrics.target": f"""[Unit]
Description=Netrune metrics stack
Wants=netrune-collector.service netrune-exporter.service
Wants=netrune-victoriametrics.service netrune-vmalert.service
{grapher_want}

[Install]
WantedBy=default.target
""",
        "netrune-collector.service": _collector_unit(netrune),
        "netrune-exporter.service": f"""[Unit]
Description=Netrune metrics exposition
PartOf=netrune-metrics.target
Before=netrune-victoriametrics.service

[Service]
Type=simple
ExecStart={netrune} traffic exporter --bind {bind}{exporter_confirm}
KillSignal=SIGTERM
TimeoutStopSec=10
Restart=always
RestartSec=5
Environment=NETRUNE_PROGRESS=0

[Install]
WantedBy=netrune-metrics.target
""",
        "netrune-victoriametrics.service": f"""[Unit]
Description=VictoriaMetrics for Netrune
PartOf=netrune-metrics.target
Wants=netrune-exporter.service
After=netrune-exporter.service

[Service]
Type=simple
ExecStart={victoria_metrics} \
  -storageDataPath={root}/storage \
  -retentionPeriod={retention} \
  -promscrape.config={root}/scrape.yml \
  -httpListenAddr={storage_bind or vm_url.split('//', 1)[-1]}{vm_auth}
Restart=always
RestartSec=10

[Install]
WantedBy=netrune-metrics.target
""",
        "netrune-vmalert.service": f"""[Unit]
Description=vmalert for Netrune
PartOf=netrune-metrics.target
Wants=netrune-victoriametrics.service
After=netrune-victoriametrics.service

[Service]
Type=simple
# Replace -notifier.blackhole with -notifier.url=http://<alertmanager>:9093 when
# there is somewhere for alerts to go. vmalert refuses to start with alerting
# rules and no notifier at all.
ExecStart={vmalert} \
  -datasource.url={vm_url} \
  -remoteWrite.url={vm_url} \
  -remoteRead.url={vm_url} \
  -rule={root}/alerts.yml \
  -notifier.blackhole \
  -httpListenAddr=127.0.0.1:8880
Restart=always
RestartSec=10

[Install]
WantedBy=netrune-metrics.target
""",
    }


def grapher_native_unit(root: Path, grapher: Any, port: int, binary: str) -> str:
    """Run the grapher directly, with no container runtime in the way.

    A container runtime on a laptop is something that gets closed, and when it
    stops the dashboards stop with it while every other part of the stack keeps
    running. Nothing about a dashboard needs isolation from the machine it is
    already reading data on.
    """
    environment = "\n".join(f"Environment={name}={value}"
                             for name, value in sorted(grapher.native_environment(root).items()))
    return f"""[Unit]
Description={grapher.display_name} dashboards for Netrune
PartOf=netrune-metrics.target
Wants=netrune-victoriametrics.service
After=netrune-victoriametrics.service

[Service]
Type=simple
{environment}
Environment=GF_SERVER_HTTP_PORT={port}
ExecStart={binary} server --homepath=/usr/share/grafana
Restart=always
RestartSec=10

[Install]
WantedBy=netrune-metrics.target
"""


def grapher_container_unit(root: Path, grapher: Grapher, port: int) -> str:
    """Run the selected grapher in a container, with its own provisioning mounted.

    Every grapher is published with -p rather than given host networking: under
    Docker Desktop, --network host joins the Docker VM's namespace rather than
    the WSL distro's, and the published port would be unreachable. A grapher
    that proxies queries itself gets a host alias through container_args instead.
    """
    mounts = " \\\n".join(f"  -v {mount}" for mount in grapher.container_mounts(root))
    env = " \\\n".join(f"  -e {name}={value}" for name, value in sorted(grapher.container_env().items()))
    extra = " \\\n".join(f"  {arg}" for arg in grapher.container_args())
    parts = [f"ExecStart=/usr/bin/docker run --rm --name netrune-{grapher.name} \\",
             f"  -p 127.0.0.1:{port}:{grapher.default_port} \\"]
    if extra:
        parts.append(extra + " \\")
    if mounts:
        parts.append(mounts + " \\")
    if env:
        parts.append(env + " \\")
    parts.append(f"  {grapher.image}")
    exec_start = "\n".join(parts)
    return f"""[Unit]
Description={grapher.display_name} dashboards for Netrune
PartOf=netrune-metrics.target
Wants=netrune-victoriametrics.service
After=netrune-victoriametrics.service

[Service]
Type=simple
ExecStartPre=-/usr/bin/docker rm -f netrune-{grapher.name}
{exec_start}
ExecStop=/usr/bin/docker stop netrune-{grapher.name}
Restart=always
RestartSec=10
TimeoutStartSec=120

[Install]
WantedBy=netrune-metrics.target
"""


def readme(paths: Mapping[str, Path], bind: str, vm_url: str, grapher: Any,
           port: int, dashboards: Sequence[Any], *, storage_bind: str = "") -> str:
    base_url = f"http://127.0.0.1:{port}"
    vm_listen = storage_bind or vm_url.split("//", 1)[-1]
    vm_auth_flags = (f" \\\n  -httpAuth.username={VM_CREDENTIAL_USER} "
                      f"-httpAuth.password=file://{paths['root'] / VM_CREDENTIAL_FILE}") if storage_bind else ""
    push_note = ""
    if storage_bind:
        token = _victoriametrics_credential(paths["root"])
        push_url = f"http://{VM_CREDENTIAL_USER}:{token}@{storage_bind}"
        push_note = (
            "\n## Accepting a remote poller's push\n\n"
            f"This bind accepts writes from anywhere that can reach {storage_bind}, gated by "
            f"the token in `{paths['root'] / VM_CREDENTIAL_FILE}` (mode 0600, generated once and "
            "kept -- rotating it means editing the file and re-pasting the URL below everywhere "
            "it is used). Give the remote poller this exact URL:\n\n"
            f"```\nnetrune config set traffic_push_url {push_url}\n```\n")
    links = "\n".join(f"- {d.title}: <{grapher.dashboard_url(base_url, d)}>" for d in dashboards)
    grapher_row = (f"| {grapher.display_name} | Dashboards, provisioned from files. | {base_url} |"
                   if grapher.image else
                   "| vmui | Ad-hoc querying, built into VictoriaMetrics. | "
                   f"{vm_url}/vmui |")
    return f"""# Netrune metrics stack

Generated by `netrune traffic stack init`. Regenerate at any time; these files
are derived from the watchlist and are safe to overwrite.

## What owns what

| Component | Owns | Reached at |
| --- | --- | --- |
| `netrune traffic daemon` | Talking to devices. Holds the SNMP credentials. | local process |
| `netrune traffic exporter` | Publishing raw counters. | http://{bind}/metrics |
| VictoriaMetrics | Retention and querying. Scrapes the exporter. | {vm_url} |
| vmalert | Alerting, evaluated against stored data. | http://127.0.0.1:8880 |
{grapher_row}
{push_note}
Netrune never computes a rate for this pipeline. The exposition carries raw
monotonic counters and MetricsQL derives throughput, errors, and utilisation at
query time, which is also what makes counter resets handle themselves.

The grapher is interchangeable. Netrune publishes Prometheus exposition and
VictoriaMetrics answers the Prometheus query API, so any tool that speaks it can
read this data. `--grapher` selects which one gets provisioning files generated
for it; the collector, the exposition, the storage, and the alert rules do not
change.

## Dashboards

{links}

## Making it persist

Generated systemd **user** units live in `{paths['units']}`. They need no root:

```bash
mkdir -p ~/.config/systemd/user
cp {paths['units']}/*.service {paths['units']}/*.target ~/.config/systemd/user/
systemctl --user daemon-reload
systemctl --user enable --now netrune-metrics.target
loginctl enable-linger "$USER"      # keeps them running with no session open
```

`netrune-metrics.target` pulls in the collector, the exposition,
VictoriaMetrics, vmalert, and the grapher. Ordering matters on a cold start: the
exposition comes up before VictoriaMetrics, or the first scrapes record the
collector as down.

```bash
systemctl --user status netrune-metrics.target
journalctl --user -u netrune-collector -f
netrune traffic verify              # check every link in the chain
```

Editing the watchlist does not need a restart. The collector re-reads it every
tick, so `netrune traffic watch`, `pause`, `resume`, and `unwatch` take effect
within seconds.

## Running it by hand instead

Native, with the AUR packages `victoriametrics-bin` and `vmutils-bin`:

```bash
victoria-metrics -storageDataPath={paths['root']}/storage \\
  -retentionPeriod=90d -promscrape.config={paths['scrape']} \\
  -httpListenAddr={vm_listen}{vm_auth_flags} &
vmalert -datasource.url={vm_url} -remoteWrite.url={vm_url} \\
  -remoteRead.url={vm_url} -rule={paths['alerts']} \\
  -notifier.blackhole -httpListenAddr=127.0.0.1:8880 &
```

`-notifier.blackhole` evaluates every rule and keeps firing alerts visible at
<http://127.0.0.1:8880> and in the `ALERTS` series, without routing them
anywhere. vmalert refuses to start with alerting rules and no notifier at all,
so replace the flag with `-notifier.url=http://<alertmanager>:9093` when there
is somewhere for alerts to go.

Or bring it all up together:

```bash
cd {paths['root']} && docker compose up -d
```

## Order of operations

1. Start the collector: `netrune traffic daemon`
2. Start the exporter: `netrune traffic exporter`
3. Start VictoriaMetrics, then vmalert, then the grapher.
4. Import the history collected before the stack existed:
   `netrune traffic backfill`

## Checking it

```bash
netrune traffic verify              # every link, end to end
curl -s http://{bind}/metrics | head
curl -s '{vm_url}/api/v1/query?query=netrune_interface_up'
curl -s http://127.0.0.1:8880/api/v1/rules   # every rule should have no lastError
```

Imported history is older than an instant query looks back, so query it over a
range rather than at a moment:

```bash
curl -s -G '{vm_url}/api/v1/query_range' \\
  --data-urlencode 'query=netrune_history_interface_receive_bits_per_second' \\
  --data-urlencode "start=$(date -d '7 days ago' +%s)" \\
  --data-urlencode "end=$(date +%s)" --data-urlencode 'step=300'
```
"""


def compose_file(bind: str, vm_url: str, retention: str, grapher: Grapher, port: int, *, storage_bind: str = "") -> str:
    """Everything but the collector, which stays on the host with the credentials."""
    vm_listen = storage_bind or vm_url.split("//", 1)[-1]
    vm_auth_args = (
        f'\n      - "-httpAuth.username={VM_CREDENTIAL_USER}"'
        f'\n      - "-httpAuth.password=file:///etc/netrune/{VM_CREDENTIAL_FILE}"'
    ) if storage_bind else ""
    vm_auth_volume = f"\n      - ./{VM_CREDENTIAL_FILE}:/etc/netrune/{VM_CREDENTIAL_FILE}:ro" if storage_bind else ""
    if grapher.image:
        mounts = "\n".join(f"      - {mount.replace(str(Path.cwd()), '.')}"
                           for mount in grapher.container_mounts(Path(".")))
        env = "".join(f"\n      {name}: \"{value}\"" for name, value in sorted(grapher.container_env().items()))
        network = f"    ports:\n      - \"127.0.0.1:{port}:{grapher.default_port}\""
        hosts = grapher.container_args()
        if hosts:
            aliases = "\n".join(f"      - \"{arg.split('=', 1)[1]}\"" for arg in hosts
                                if arg.startswith("--add-host="))
            if aliases:
                network += f"\n    extra_hosts:\n{aliases}"
        named = sorted({mount.split(":", 1)[0] for mount in grapher.container_mounts(Path("."))
                        if not mount.startswith((".", "/"))})
        volumes = ("\n\nvolumes:\n" + "\n".join(f"  {name}:" for name in named)) if named else ""
        grapher_block = f"""
  {grapher.name}:
    image: {grapher.image}
{network}
    volumes:
{mounts}
    environment:{env or " {}"}
    depends_on: [victoriametrics]
    restart: unless-stopped
"""
    else:
        grapher_block = ""
        volumes = ""

    return f"""# Generated by 'netrune traffic stack init'.
#
# The collector is not in here. It runs on the host, holds the SSH and SNMP
# credentials, and is reached through host networking so that a container never
# needs them.
services:
  victoriametrics:
    image: victoriametrics/victoria-metrics:latest
    command:
      - "-storageDataPath=/storage"
      - "-retentionPeriod={retention}"
      - "-promscrape.config=/etc/netrune/scrape.yml"
      - "-httpListenAddr={vm_listen}"{vm_auth_args}
    network_mode: host
    volumes:
      - ./storage:/storage
      - ./scrape.yml:/etc/netrune/scrape.yml:ro{vm_auth_volume}
    restart: unless-stopped

  vmalert:
    image: victoriametrics/vmalert:latest
    command:
      - "-datasource.url={vm_url}"
      - "-remoteWrite.url={vm_url}"
      - "-remoteRead.url={vm_url}"
      - "-rule=/etc/netrune/alerts.yml"
      - "-notifier.blackhole"
      - "-httpListenAddr=127.0.0.1:8880"
    network_mode: host
    volumes:
      - ./alerts.yml:/etc/netrune/alerts.yml:ro
    depends_on: [victoriametrics]
    restart: unless-stopped
{grapher_block}{volumes}
"""


KEPT_DIR = "dashboards-kept"


def kept_dashboard_dir(root: Path) -> Path:
    return root / KEPT_DIR


def _kept_dashboards(root: Path) -> Dict[str, str]:
    """Edited dashboards, by uid, saved from the browser and kept."""
    directory = kept_dashboard_dir(root)
    if not directory.is_dir():
        return {}
    return {path.stem: path.read_text(encoding="utf-8")
            for path in sorted(directory.glob("*.json"))}


def stack_files(bind: str, vm_url: str, scrape_interval: int, retention: str, root: Path,
                *, grapher_name: str = "grafana", grapher_port: int = 0,
                unit_dir: Optional[Path] = None, confirmed_bind: bool = False,
                grapher_native: bool = True, role: str = ROLE_FULL,
                series_colors: Optional[Mapping[str, str]] = None,
                export_path: str = "",
                push_url: str = "",
                links: Sequence[Any] = (),
                org: str = "",
                grapher_bind: str = "",
                storage_bind: str = "",
                binaries: Optional[Mapping[str, str]] = None) -> Dict[Path, str]:
    """Every file the stack needs, keyed by the path it belongs at."""
    if role == ROLE_COLLECTOR:
        # A poller collects and nothing else, so it needs no scrape config, no
        # alert rules, no dashboards, and no compose file. Generating them and
        # leaving them unused would only invite somebody to start them.
        units_root = unit_dir or (root / "systemd")
        return {units_root / name: body for name, body in
                systemd_units(root, bind, vm_url, retention,
                              (binaries or {}).get("netrune", "netrune"),
                              "", "", role=ROLE_COLLECTOR,
                              export_path=export_path, push_url=push_url).items()}
    grapher = get_grapher(grapher_name)
    if grapher is None:
        raise ValueError(f"unknown grapher '{grapher_name}'; choose from {', '.join(grapher_names())}")
    if org and hasattr(grapher, "org"):
        grapher.org = org
    if grapher_bind and hasattr(grapher, "http_addr"):
        grapher.http_addr = grapher_bind
    port = grapher_port or grapher.default_port
    found = dict(binaries or {})
    units_root = unit_dir or (root / "systemd")
    dashboards = all_dashboards(series_colors, links)
    #: Dashboards an operator edited in the browser and chose to keep. Written
    #: verbatim in place of the generated one, because the whole point of
    #: keeping it is that it is not what the generator would produce.
    kept = _kept_dashboards(root)

    grapher_unit = f"netrune-{grapher.name}.service" if grapher.image else ""
    unit_bodies = systemd_units(
        root, bind, vm_url, retention,
        found.get("netrune", "netrune"),
        found.get("victoria-metrics", "victoria-metrics"),
        found.get("vmalert", "vmalert"),
        grapher_unit=grapher_unit, confirmed_bind=confirmed_bind,
        storage_bind=storage_bind,
    )
    if grapher_unit:
        # Native when the binary is on this machine, container otherwise. The
        # dashboards are identical either way; only what supervises them differs.
        native_binary = next(
            (found[name] for name in getattr(grapher, "NATIVE_BINARIES", ()) if found.get(name)), "")
        if native_binary and grapher_native:
            unit_bodies[grapher_unit] = grapher_native_unit(root, grapher, port, native_binary)
        else:
            unit_bodies[grapher_unit] = grapher_container_unit(root, grapher, port)

    files: Dict[Path, str] = {units_root / name: body for name, body in unit_bodies.items()}
    native_binary = next(
        (found[name] for name in getattr(grapher, "NATIVE_BINARIES", ()) if found.get(name)), "")
    running_native = bool(native_binary and grapher_native)
    try:
        files.update(grapher.files(
            dashboards,
            grapher.resolve_datasource_url(vm_url, containerized=not running_native and bool(grapher.image)),
            root, native=running_native, kept=kept))
    except TypeError:
        # An adapter that has no native deployment takes the container form.
        files.update(grapher.files(
            dashboards, grapher.resolve_datasource_url(vm_url, containerized=bool(grapher.image)), root))
    files.update({
        root / "scrape.yml": scrape_config(bind, scrape_interval),
        root / "alerts.yml": alert_rules(),
        root / "docker-compose.yml": compose_file(bind, vm_url, retention, grapher, port, storage_bind=storage_bind),
        root / "README.md": readme(
            {"root": root, "scrape": root / "scrape.yml", "alerts": root / "alerts.yml",
             "units": units_root},
            bind, vm_url, grapher, port, dashboards, storage_bind=storage_bind),
    })
    if storage_bind:
        files[root / VM_CREDENTIAL_FILE] = _victoriametrics_credential(root)
    return files

"""Provisioning files for the metrics stack Netrune feeds.

Netrune owns collection and evidence. VictoriaMetrics owns retention and
querying. Perses owns presentation. vmalert owns alerting. Everything this
module writes is a file those components read at startup, so the stack is
reproducible from the watchlist rather than clicked together in a UI.

Rates are computed in MetricsQL, never here. The exposition publishes raw
counters and the queries below turn them into throughput, errors, utilisation,
and interface status.
"""

from __future__ import annotations

import secrets
from pathlib import Path
from typing import Any, Dict, Mapping, Optional, Sequence


"""Deterministic public references generated from the command registry."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Iterable, Mapping


GENERATED_HEADER = "Generated by generate_reference.py; do not edit by hand."


def _public_command(value: str) -> str:
    tokens = value.split()
    if tokens:
        tokens[0] = "netops"
    return " ".join(tokens)


def _registry_rows(registry: Iterable[Any]) -> list[dict[str, Any]]:
    rows = []
    for spec in registry:
        row = spec.as_dict() if hasattr(spec, "as_dict") else dict(spec)
        row["command"] = _public_command(str(row.get("command") or ""))
        rows.append(row)
    return sorted(rows, key=lambda row: (str(row.get("domain")), str(row.get("id"))))


def markdown_reference(registry: Iterable[Any], version: str) -> str:
    rows = _registry_rows(registry)
    domains: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        domains.setdefault(str(row.get("domain") or "general"), []).append(row)
    lines = [
        "# NetOps Command Reference",
        "",
        f"<!-- {GENERATED_HEADER} -->",
        "",
        f"Version: `{version}`",
        "",
        "Every entry below comes from the registry used by the CLI, TUI Action Hub, previews, jobs, and local API.",
        "",
    ]
    for domain, items in domains.items():
        lines += [f"## {domain}", "", "| Command ID | Invocation | Safety | Output | Purpose |", "|---|---|---|---|---|"]
        for row in items:
            purpose = str(row.get("description") or "").replace("|", "\\|")
            invocation = str(row.get("command") or "").replace("|", "\\|")
            lines.append(
                f"| `{row['id']}` | `{invocation}` | `{row.get('safety_class')}` | `{row.get('output_type')}` | {purpose} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def man_page(registry: Iterable[Any], topics: Mapping[str, Any], version: str) -> str:
    rows = _registry_rows(registry)
    lines = [
        '.TH NETOPS 1 "" "NetOps ' + version + '" "User Commands"',
        ".SH NAME",
        "netops \\- local-first network operations platform",
        ".SH SYNOPSIS",
        ".B netops",
        "[--profile NAME] DOMAIN ACTION [ARGUMENTS] [GLOBAL FLAGS]",
        ".SH DESCRIPTION",
        "NetOps provides profile-isolated inventory, diagnostics, ingest, plugins, and bounded path inspection.",
        ".SH DOMAINS",
    ]
    for name, topic in topics.items():
        lines += [f".TP\n.B {name}", str(topic.get("summary") or "")]
    lines += [".SH REGISTERED COMMANDS"]
    for row in rows:
        lines += [f".TP\n.B {row['id']}", _public_command(str(row.get("command") or "")) + " - " + str(row.get("description") or "")]
    lines += [
        ".SH FILES",
        "Configuration follows XDG base directories and is isolated under profiles/PROFILE.",
        ".SH SECURITY",
        "Secret values use named encrypted storage and must not be placed in command arguments or TOML files.",
        ".SH SEE ALSO",
        "netops help, netops commands list, netops diagnose doctor",
        f'.\\" {GENERATED_HEADER}',
    ]
    return "\n".join(lines) + "\n"


def bash_completion(topics: Mapping[str, Any]) -> str:
    domains = " ".join(topics)
    cases = []
    for domain, topic in topics.items():
        actions = " ".join(topic.get("actions", {}))
        cases.append(f"            {domain}) COMPREPLY=( $(compgen -W '{actions}' -- \"$cur\") ) ;;")
    return f"""# {GENERATED_HEADER}
_netops_complete() {{
    local cur prev domain
    COMPREPLY=()
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    domain="${{COMP_WORDS[1]}}"
    if (( COMP_CWORD == 1 )); then
        COMPREPLY=( $(compgen -W '{domains}' -- "$cur") )
        return
    fi
    if (( COMP_CWORD == 2 )); then
        case "$domain" in
{chr(10).join(cases)}
        esac
    fi
}}
complete -F _netops_complete netops netop
"""


def zsh_completion(topics: Mapping[str, Any]) -> str:
    domains = " ".join(f"'{name}:{str(topic.get('summary') or '').replace(chr(39), '')}'" for name, topic in topics.items())
    cases = []
    for domain, topic in topics.items():
        actions = " ".join(f"'{name}:{str(doc.get('about') or '').replace(chr(39), '')}'" for name, doc in topic.get("actions", {}).items())
        cases.append(f"      {domain}) _describe 'action' '({actions})' ;;")
    return f"""#compdef netops netop
# {GENERATED_HEADER}
_netops() {{
  local domain=$words[2]
  if (( CURRENT == 2 )); then
    _describe 'domain' '({domains})'
  elif (( CURRENT == 3 )); then
    case $domain in
{chr(10).join(cases)}
    esac
  else
    _arguments '*:argument:'
  fi
}}
_netops "$@"
"""


def fish_completion(topics: Mapping[str, Any]) -> str:
    lines = [f"# {GENERATED_HEADER}", "complete -c netops -f", "complete -c netop -f"]
    for command in ("netops", "netop"):
        for domain, topic in topics.items():
            summary = str(topic.get("summary") or "").replace("'", "")
            lines.append(f"complete -c {command} -n '__fish_use_subcommand' -a {domain} -d '{summary}'")
            for action, doc in topic.get("actions", {}).items():
                about = str(doc.get("about") or "").replace("'", "")
                lines.append(f"complete -c {command} -n '__fish_seen_subcommand_from {domain}' -a {action} -d '{about}'")
    return "\n".join(lines) + "\n"


def generated_files(registry: Iterable[Any], topics: Mapping[str, Any], version: str) -> dict[str, str]:
    rows = _registry_rows(registry)
    return {
        "docs/reference/commands.md": markdown_reference(rows, version),
        "docs/reference/command-registry.json": json.dumps({"schema_version": 1, "version": version, "commands": rows}, indent=2, sort_keys=True) + "\n",
        "man/netops.1": man_page(rows, topics, version),
        "completions/netops.bash": bash_completion(topics),
        "completions/_netops": zsh_completion(topics),
        "completions/netops.fish": fish_completion(topics),
    }


def write_or_check(root: Path, registry: Iterable[Any], topics: Mapping[str, Any], version: str, *, check: bool = False) -> list[str]:
    changed: list[str] = []
    for relative, content in generated_files(registry, topics, version).items():
        path = Path(root) / relative
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        if existing != content:
            changed.append(relative)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    return changed
